"""Reproducible end-to-end ML run. Usage:  python -I run_ml.py [--seed 42] [--out artifacts]

Writes: artifacts/load_model.joblib, artifacts/failure_model.joblib, artifacts/q_table.npy,
        artifacts/metrics.json, model_card.md
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
import data_gen as g  # noqa: E402
import failure as fl  # noqa: E402
import forecast as fc  # noqa: E402
import rl_qlearning as rl  # noqa: E402

VERSION = "0.1.0"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def seed_robustness(seeds=(0, 1, 2, 3, 4)) -> dict:
    """Repeat the failure-model comparison over independent synthetic worlds."""
    acc: dict[str, list] = {}
    for sd in seeds:
        F, A = g.make_topology(seed=sd)
        res = fl.run(g.make_asset_snapshots(F, A, seed=sd), seed=sd)["results"]
        for name, r in res.items():
            acc.setdefault(name, []).append((r["test"]["auc"], r["test"]["pr_auc"]))
    return {n: {"auc_mean": float(np.mean([a for a, _ in v])), "auc_sd": float(np.std([a for a, _ in v])),
                "pr_auc_mean": float(np.mean([p for _, p in v])), "pr_auc_sd": float(np.std([p for _, p in v]))}
            for n, v in acc.items()} | {"seeds": list(seeds)}


def main(seed: int = 42, out: Path = HERE / "artifacts") -> dict:
    out.mkdir(parents=True, exist_ok=True)
    feeders, assets = g.make_topology(seed)
    load = g.make_load(feeders, seed=seed)
    snaps = g.make_asset_snapshots(feeders, assets, seed=seed)

    f = fc.run(load, seed)
    c = fl.run(snaps, seed)
    Q = rl.train_q(seed=seed)
    rl_eval = rl.evaluate_policies(Q)
    robust = seed_robustness()

    meta = {"version": VERSION, "seed": seed, "created": datetime.now(timezone.utc).isoformat(), "synthetic": True}
    joblib.dump({"model": f["model"], "features": f["features"], "interval": f["interval"], "meta": meta}, out / "load_model.joblib")
    joblib.dump({"model": c["model"], "features": c["features"], "meta": meta}, out / "failure_model.joblib")
    np.save(out / "q_table.npy", Q)

    metrics = {
        "meta": meta,
        "data": {"load_rows": len(load), "snapshot_rows": len(snaps), "load_missing_rate": float(load.load_kw.isna().mean()),
                 "failure_base_rate": float(snaps.fail_30d.mean())},
        "forecast": {k: f[k] for k in ("selected", "results", "interval", "n")},
        "failure": {k: c[k] for k in ("selected", "results", "fairness_test", "n", "train_base_rate")},
        "failure_seed_robustness": robust,
        "rl": rl_eval,
        "artifact_sha256": {p.name: sha256(p) for p in sorted(out.glob("*.joblib")) + [out / "q_table.npy"]},
    }
    (out / "metrics.json").write_text(json.dumps(metrics, indent=2))
    (HERE / "model_card.md").write_text(model_card(metrics))
    return metrics


def model_card(m: dict) -> str:
    F, C, R, rob = m["forecast"], m["failure"], m["rl"], m["failure_seed_robustness"]
    fsel, csel = F["selected"], C["selected"]
    fr = F["results"]
    fair = C["fairness_test"]
    rows_f = "\n".join(f"| {k} | {v['val']['mae']:.1f} | {v['test']['mae']:.1f} | {v['test']['mape']*100:.1f}% |"
                       for k, v in fr.items())
    rows_c = "\n".join(f"| {k} | {v['test']['auc']:.3f} | {v['test']['pr_auc']:.3f} | {v['test']['brier']:.3f} |"
                       for k, v in C["results"].items())
    rows_r = "\n".join(f"| {k} | {v['auc_mean']:.3f} ± {v['auc_sd']:.3f} | {v['pr_auc_mean']:.3f} ± {v['pr_auc_sd']:.3f} |"
                       for k, v in rob.items() if k != "seeds")
    rows_rl = "\n".join(f"| {k} | {v['mean_reward']:.2f} ± {v['se']:.2f} | {v['safety_violations']} |" for k, v in R.items())

    def zone_rows(d):
        return "\n".join(f"| {z} | {v['failures']} | {'n/a' if v['recall'] is None else f'{v['recall']:.2f}'} | {v['flag_rate']:.2f} |"
                         for z, v in d.items() if isinstance(v, dict))
    gl, st = fair["global_top_k"], fair["zone_stratified_top_k"]
    iv = F["interval"]
    return f"""# Model Card — CedarLight Grid Models v{m['meta']['version']}
*Synthetic data only. Seed {m['meta']['seed']}. Generated by `run_ml.py`; numbers below are produced by that run.*

## 1. Intended use
Decision support for grid planners: (a) 24-hour-ahead feeder load forecasts, (b) 30-day asset failure-risk ranking to prioritise inspections. Outputs are **recommendations**; schedule proposals stay approval-gated. **Not** for real utility operations, switching, load shedding or customer-impacting decisions.

## 2. Data
Fictitious: 3 zones, 12 feeders, 60 transformers. {m['data']['load_rows']:,} hourly feeder rows ({m['data']['load_missing_rate']*100:.1f}% readings missing); {m['data']['snapshot_rows']:,} monthly asset snapshots (failure base rate {m['data']['failure_base_rate']*100:.1f}%). Zone C is deliberately older and has a higher true failure rate. The synthetic failure process drifts mildly upward over time (aging fleet).

## 3. Load forecaster — selected: `{fsel}` (chosen on validation MAE)
Features: hour (sin/cos), weekday, weekend, temperature signal, storm flag, 24h and 168h lags (lags only from data ≥24h old), feeder id. Time-ordered split ({F['n']['train']:,}/{F['n']['val']:,}/{F['n']['test']:,}); 4-fold `TimeSeriesSplit` CV on train.

| Model | Val MAE (kW) | Test MAE (kW) | Test MAPE |
|---|---|---|---|
{rows_f}

**Interval:** empirical 90% band from validation residuals ({iv['lo_rel']*100:+.1f}% / {iv['hi_rel']*100:+.1f}%). **Test coverage {iv['test_coverage']*100:.1f}% vs 90% target** — slightly under-covered, so intervals should be treated as optimistic; widen or recalibrate before relying on them.

## 4. Failure-risk classifier — selected: `{csel}` (highest validation PR-AUC; within 0.01 the simpler model wins)
Features: age, observed condition score, load ratio, heat hours, trailing-12-month faults. Time-ordered split by snapshot month ({C['n']['train']}/{C['n']['val']}/{C['n']['test']}). Class imbalance (~9% positives) is handled by evaluating ranking metrics; models are **not** class-reweighted, because the agent consumes the predicted probabilities and reweighting would inflate them. Brier score checks probability quality.

| Model | Test AUC | Test PR-AUC | Brier |
|---|---|---|---|
{rows_c}

**Seed robustness (5 independent synthetic worlds, test split):**

| Model | AUC | PR-AUC |
|---|---|---|
{rows_r}

**Honest reading:** ranking quality (AUC / PR-AUC) of the learned models is close to the age-only and condition-only baselines, with differences inside seed-to-seed noise. A single test split has ~{C['n']['test']} rows, so differences of a few AUC points should not be over-interpreted. The learned models' main practical benefit is **usable probabilities**: the baselines output raw scores, so their Brier values above are not comparable; among the probability models, lower Brier is better. The neural net did not beat logistic regression.

## 5. Fairness / coverage check (test split, flag top 10% of assets)
**Global ranking** — overall recall {gl['overall_recall']:.2f}, recall gap between zones {gl['recall_gap']:.2f}

| Zone | Failures | Recall | Share of zone flagged |
|---|---|---|---|
{zone_rows(gl)}

**Zone-stratified quota** — overall recall {st['overall_recall']:.2f}, recall gap {st['recall_gap']:.2f}

| Zone | Failures | Recall | Share of zone flagged |
|---|---|---|---|
{zone_rows(st)}

The global ranking is accurate but concentrates nearly all inspections in Zone C (it truly has the highest failure rate), leaving Zones A and B effectively uncovered. A per-zone quota narrows the gap at the cost of overall recall. **This trade-off is a policy decision for human operators;** the agent surfaces both options and does not choose silently.

## 6. Reinforcement-learning component (tabular Q-learning, toy inspection-selection MDP)
State (risk bucket, inspections left, blackout flag, position in the day); actions skip/inspect; reward = −inspection cost − failure cost. **Safety:** `inspect` is masked during blackout (storm) or when the crew budget is exhausted — in exploration *and* execution. Exact dynamic programming gives an optimum of about −6.58 reward per episode.

| Policy | Mean reward ± SE | Safety violations |
|---|---|---|
{rows_rl}

Q-learning matches the hand-written greedy threshold and the DP optimum within noise; it does **not** significantly improve on it in this small MDP. It is kept behind the `use_rl_policy` feature flag (default off). A first version that omitted the position in the day from the state performed no better than never inspecting — a Markov-state design error caught by comparison with DP.

## 7. Limitations and risks
- All data and ground-truth relationships are synthetic; real-world performance is unknown.
- Forecast ignores holidays and has no explicit seasonal drift model; intervals under-cover slightly.
- Small asset test set; ranking metrics are noisy. Parameters of the Bayesian network in `04_uncertainty/` are not yet fitted from this data.
- Models use no personal data; no customer-level information is modelled.
- Neural network: scikit-learn `MLPClassifier` (PyTorch was unavailable in this environment); it did not outperform logistic regression.

## 8. Governance
Artifacts are hash-recorded in `artifacts/metrics.json`. Model outputs enter the agent only as `Proposition`/`InferenceTrace` evidence and never upgrade an entailment status. Retrain and re-evaluate when data drift or coverage drops below thresholds in `configs/agent.yaml`.
"""


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", type=Path, default=HERE / "artifacts")
    a = ap.parse_args()
    main(a.seed, a.out)
    print("done:", a.out)
